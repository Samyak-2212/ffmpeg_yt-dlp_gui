# setup-env.ps1 — Windows environment setup for FFmpeg Android cross-compilation
#
# Downloads Android NDK r27c and installs required MSYS2 packages.
# Run once before the first build.
#
# Usage: .\setup-env.ps1 [-NdkDir <path>] [-SkipMsys2] [-SkipNdk]
#
param(
    [string]$NdkDir = "C:\android-ndk-r27c",
    [switch]$SkipMsys2,
    [switch]$SkipNdk,
    [string]$Msys2Dir = "C:\msys64"
)

$ErrorActionPreference = "Stop"

Write-Host "=== FFmpeg Android Build Environment Setup ===" -ForegroundColor Cyan
Write-Host ""

# ─────────────────────────────────────────────────────────────────────────────
# 1. Check MSYS2
# ─────────────────────────────────────────────────────────────────────────────
if (-not (Test-Path "$Msys2Dir\usr\bin\bash.exe")) {
    Write-Error "MSYS2 not found at $Msys2Dir. Please install MSYS2 from https://www.msys2.org/ first."
    exit 1
}
Write-Host "[OK] MSYS2 found at $Msys2Dir" -ForegroundColor Green

# ─────────────────────────────────────────────────────────────────────────────
# 2. Install MSYS2 packages
# ─────────────────────────────────────────────────────────────────────────────
if (-not $SkipMsys2) {
    Write-Host ""
    Write-Host "Installing required MSYS2 packages..." -ForegroundColor Yellow

    $packages = @(
        "gcc",
        "autoconf",
        "automake",
        "libtool",
        "make",
        "pkg-config",
        "nasm",
        "yasm",
        "diffutils",
        "git",
        "wget",
        "unzip"
    )

    $pkgList = $packages -join " "
    $pacmanCmd = "pacman -S --needed --noconfirm $pkgList"

    Write-Host "  Running: $pacmanCmd"
    & "$Msys2Dir\usr\bin\bash.exe" -lc $pacmanCmd
    if ($LASTEXITCODE -ne 0) {
        Write-Warning "Some MSYS2 packages may have failed to install. Check output above."
    } else {
        Write-Host "[OK] MSYS2 packages installed" -ForegroundColor Green
    }
}

# ─────────────────────────────────────────────────────────────────────────────
# 3. Download Android NDK r27c
# ─────────────────────────────────────────────────────────────────────────────
if (-not $SkipNdk) {
    Write-Host ""
    Write-Host "Checking Android NDK..." -ForegroundColor Yellow

    if (Test-Path "$NdkDir\ndk-build.cmd") {
        Write-Host "[OK] NDK already found at $NdkDir" -ForegroundColor Green
    } else {
        $ndkZip = "$env:TEMP\android-ndk-r27c-windows.zip"
        $ndkUrl = "https://dl.google.com/android/repository/android-ndk-r27c-windows.zip"

        Write-Host "  Downloading NDK r27c from Google (~750MB)..."
        Write-Host "  URL: $ndkUrl"
        Write-Host "  Destination: $ndkZip"

        $progressPref = $ProgressPreference
        $ProgressPreference = 'SilentlyContinue'
        try {
            Invoke-WebRequest -Uri $ndkUrl -OutFile $ndkZip -UseBasicParsing
        } finally {
            $ProgressPreference = $progressPref
        }

        Write-Host "  Extracting NDK to C:\..."
        Expand-Archive -Path $ndkZip -DestinationPath "C:\" -Force
        Remove-Item $ndkZip -Force

        if (Test-Path "$NdkDir\ndk-build.cmd") {
            Write-Host "[OK] NDK r27c extracted to $NdkDir" -ForegroundColor Green
        } else {
            Write-Error "NDK extraction failed. Expected $NdkDir\ndk-build.cmd to exist."
            exit 1
        }
    }
}

# ─────────────────────────────────────────────────────────────────────────────
# 4. Write environment config for build.sh
# ─────────────────────────────────────────────────────────────────────────────
$configContent = @"
# Auto-generated by setup-env.ps1 — DO NOT COMMIT
# Source this file in MSYS2 before running build.sh
export NDK_HOME="/c/android-ndk-r27c"
export ANDROID_NDK_HOME="/c/android-ndk-r27c"
export FFMPEG_SRC="/c/Users/naska/OneDrive/Documents/GitHub/ffmpeg-9.0.2"
export BUILD_ROOT="/c/Users/naska/OneDrive/Documents/GitHub/ffmpeg_yt-dlp_gui"
export ANDROID_MIN_API=24
"@

$configContent | Out-File -FilePath "$PSScriptRoot\config\env.sh" -Encoding UTF8 -Force
Write-Host ""
Write-Host "[OK] Environment config written to config\env.sh" -ForegroundColor Green

# ─────────────────────────────────────────────────────────────────────────────
# 5. Summary
# ─────────────────────────────────────────────────────────────────────────────
Write-Host ""
Write-Host "=== Setup Complete ===" -ForegroundColor Cyan
Write-Host ""
Write-Host "Next steps:"
Write-Host "  1. Open MSYS2 (msys2.exe shell — NOT MinGW64 or UCRT64)"
Write-Host "  2. cd /c/Users/naska/OneDrive/Documents/GitHub/ffmpeg_yt-dlp_gui"
Write-Host "  3. ./build.sh"
Write-Host ""
Write-Host "Or build a single ABI:"
Write-Host "  ./build.sh --abi=arm64-v8a"
Write-Host "  ./build.sh --abi=armeabi-v7a"
Write-Host "  ./build.sh --abi=x86_64"
